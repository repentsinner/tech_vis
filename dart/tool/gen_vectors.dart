typedef _Basis = ({vm.Vector3 right, vm.Vector3 up});

typedef _GeometryCase = ({
  String name,
  vm.Vector3 anchor,
  _Basis camera,
  double worldUnitsPerPixel,
  CalloutQuadrant quadrant,
  LeaderLineStyle style,
});

