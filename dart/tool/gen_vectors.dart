List<({String name, double distance})> _opacityCases() {
  const near = SceneLayoutConstants.calloutOpacityNearDistance;
  const far = SceneLayoutConstants.calloutOpacityFarDistance;
  return [
    (name: 'below near', distance: near / 2),
    (name: 'at near', distance: near),
    (name: 'between near and far', distance: near + (far - near) / 4),
    (name: 'at far', distance: far),
    (name: 'beyond far', distance: far * 2),
  ];
}

List<double> _vector(vm.Vector v) => List.of(v.storage);

Map<String, Object?> _style(LeaderLineStyle style) => {
  'lineWidth': style.lineWidth,
  'gapPixels': style.gapPixels,
  'angledLengthPixels': style.angledLengthPixels,
  'horizontalLengthPixels': style.horizontalLengthPixels,
  'angleDegrees': style.angleDegrees,
};

Map<String, Object?> _geometry(_GeometryCase c) {
  final result = computeCalloutLeaderGeometry(
    anchor: c.anchor,
    cameraRight: c.camera.right,
    cameraUp: c.camera.up,
    worldUnitsPerPixel: c.worldUnitsPerPixel,
    quadrant: c.quadrant,
    style: c.style,
  );
  return {
    'name': c.name,
    'input': {
      'anchor': _vector(c.anchor),
      'cameraRight': _vector(c.camera.right),
      'cameraUp': _vector(c.camera.up),
      'worldUnitsPerPixel': c.worldUnitsPerPixel,
      'quadrant': c.quadrant.name,
      'style': _style(c.style),
    },
    'output': {
      'gapEnd': _vector(result.gapEnd),
      'elbow': _vector(result.elbow),
      'labelEdge': _vector(result.labelEdge),
    },
  };
}

/// The leader-line fixture: callout geometry, anchor alignment, and the
/// opacity ramp.
Map<String, Object?> leaderLineFixture() => {
  'computeCalloutLeaderGeometry': [
    for (final c in _geometryCases()) _geometry(c),
  ],
  'calloutAnchorAlignment': [
    for (final quadrant in CalloutQuadrant.values)
      {
        'name': quadrant.name,
        'input': {'quadrant': quadrant.name},
        'output': {'alignment': _vector(calloutAnchorAlignment(quadrant))},
      },
  ],
  'computeCalloutOpacity': [
    for (final c in _opacityCases())
      {
        'name': c.name,
        'input': {'distance': c.distance},
        'output': {'opacity': computeCalloutOpacity(c.distance)},
      },
  ],
};

/// Width of one character of the generator's stand-in typeface, as a
/// fraction of the requested height. The fixture records it beside each
/// content size it gives, so a renderer can substitute its own measure.
const _characterWidthPerHeight = 0.5;

BillboardContent _resolveText(TextRequest request) => BillboardContent(
  value: request,
  widthPixels:
      request.text.length * _characterWidthPerHeight * request.heightPixels,
  heightPixels: request.heightPixels,
);

