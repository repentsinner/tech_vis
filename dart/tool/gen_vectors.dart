/// Writes the golden-vector fixtures in `vectors/` from the Dart reference.
///
///     dart run tool/gen_vectors.dart            # write the fixtures
///     dart run tool/gen_vectors.dart --check    # exit 1 if a fixture is stale
///
/// Run from `dart/`. Each fixture records a function's inputs and the
/// outputs this package computes for them; every port tests against the
/// same files (SPEC.md, golden vectors).
library;

import 'dart:convert';
import 'dart:io';

import 'package:tech_vis/tech_vis.dart';
import 'package:vector_math/vector_math_64.dart' as vm;

/// The repository root, relative to `dart/`.
const _root = '..';

const _header =
    'GENERATED by dart/tool/gen_vectors.dart from the Dart reference. '
    'Do not edit.';

/// A camera looking down -Z, with screen axes on world X and Y.
final _axisAligned = (right: vm.Vector3(1, 0, 0), up: vm.Vector3(0, 1, 0));

/// A camera above a Z-up scene, looking along +Y.
final _zUp = (right: vm.Vector3(1, 0, 0), up: vm.Vector3(0, 0, 1));

/// An orthonormal basis with no axis aligned to the world's, so every
/// component of every output depends on both basis vectors.
final _oblique = (
  right: vm.Vector3(0.6, 0.8, 0),
  up: vm.Vector3(-0.48, 0.36, 0.8),
);

const _customStyle = LeaderLineStyle(
  lineWidth: 2,
  gapPixels: 8,
  angledLengthPixels: 40,
  horizontalLengthPixels: 30,
  angleDegrees: 45,
);

typedef _Basis = ({vm.Vector3 right, vm.Vector3 up});

typedef _GeometryCase = ({
  String name,
  vm.Vector3 anchor,
  _Basis camera,
  double worldUnitsPerPixel,
  CalloutQuadrant quadrant,
  LeaderLineStyle style,
});

List<_GeometryCase> _geometryCases() => [
  for (final quadrant in CalloutQuadrant.values)
    (
      name: '${quadrant.name}, oblique camera, default style',
      anchor: vm.Vector3(1.5, -2.25, 3),
      camera: _oblique,
      worldUnitsPerPixel: 0.125,
      quadrant: quadrant,
      style: const LeaderLineStyle(),
    ),
  (
    name: 'topRight, axis-aligned camera, one world unit per pixel',
    anchor: vm.Vector3.zero(),
    camera: _axisAligned,
    worldUnitsPerPixel: 1,
    quadrant: CalloutQuadrant.topRight,
    style: const LeaderLineStyle(),
  ),
  (
    name: 'bottomLeft, Z-up camera, far anchor',
    anchor: vm.Vector3(100, 200, -50),
    camera: _zUp,
    worldUnitsPerPixel: 0.02,
    quadrant: CalloutQuadrant.bottomLeft,
    style: const LeaderLineStyle(),
  ),
  for (final quadrant in [CalloutQuadrant.topLeft, CalloutQuadrant.bottomRight])
    (
      name: '${quadrant.name}, oblique camera, custom style',
      anchor: vm.Vector3(-4, 0.5, 7.25),
      camera: _oblique,
      worldUnitsPerPixel: 0.3,
      quadrant: quadrant,
      style: _customStyle,
    ),
];

List<({String name, double distance})> _opacityCases() {
  const near = SceneLayoutConstants.calloutOpacityNearDistance;
  const far = SceneLayoutConstants.calloutOpacityFarDistance;
  return [
    (name: 'below near', distance: near / 2),
    (name: 'at near', distance: near),
    (name: 'between near and far', distance: near + (far - near) / 4),
    (name: 'at far', distance: far),
    (name: 'beyond far', distance: far * 2),
  ];
}

List<double> _vector(vm.Vector v) => List.of(v.storage);

Map<String, Object?> _style(LeaderLineStyle style) => {
  'lineWidth': style.lineWidth,
  'gapPixels': style.gapPixels,
  'angledLengthPixels': style.angledLengthPixels,
  'horizontalLengthPixels': style.horizontalLengthPixels,
  'angleDegrees': style.angleDegrees,
};

Map<String, Object?> _geometry(_GeometryCase c) {
  final result = computeCalloutLeaderGeometry(
    anchor: c.anchor,
    cameraRight: c.camera.right,
    cameraUp: c.camera.up,
    worldUnitsPerPixel: c.worldUnitsPerPixel,
    quadrant: c.quadrant,
    style: c.style,
  );
  return {
    'name': c.name,
    'input': {
      'anchor': _vector(c.anchor),
      'cameraRight': _vector(c.camera.right),
      'cameraUp': _vector(c.camera.up),
      'worldUnitsPerPixel': c.worldUnitsPerPixel,
      'quadrant': c.quadrant.name,
      'style': _style(c.style),
    },
    'output': {
      'gapEnd': _vector(result.gapEnd),
      'elbow': _vector(result.elbow),
      'labelEdge': _vector(result.labelEdge),
    },
  };
}

/// The leader-line fixture: callout geometry, anchor alignment, and the
/// opacity ramp.
Map<String, Object?> leaderLineFixture() => {
  'computeCalloutLeaderGeometry': [
    for (final c in _geometryCases()) _geometry(c),
  ],
  'calloutAnchorAlignment': [
    for (final quadrant in CalloutQuadrant.values)
      {
        'name': quadrant.name,
        'input': {'quadrant': quadrant.name},
        'output': {'alignment': _vector(calloutAnchorAlignment(quadrant))},
      },
  ],
  'computeCalloutOpacity': [
    for (final c in _opacityCases())
      {
        'name': c.name,
        'input': {'distance': c.distance},
        'output': {'opacity': computeCalloutOpacity(c.distance)},
      },
  ],
};

/// Renders a fixture family under the header and style version every
/// fixture file carries.
String _render(Map<String, Object?> family) {
  final fixture = {
    'generated': _header,
    'styleVersion': StyleTokens.styleVersion,
    ...family,
  };
  return '${const JsonEncoder.withIndent('  ').convert(fixture)}\n';
}

void main(List<String> args) {
  final check = args.contains('--check');
  final rendered = {'vectors/leader_line.json': _render(leaderLineFixture())};

  final stale = [
    for (final MapEntry(key: path, value: text) in rendered.entries)
      if (File('$_root/$path') case final file
          when !file.existsSync() || file.readAsStringSync() != text)
        (path: path, file: file, text: text),
  ];

  if (check) {
    for (final (:path, file: _, text: _) in stale) {
      stderr.writeln('stale: $path');
    }
    if (stale.isNotEmpty) {
      stderr.writeln('run, in dart/: dart run tool/gen_vectors.dart');
      exitCode = 1;
    }
    return;
  }

  for (final (:path, :file, :text) in stale) {
    file
      ..parent.createSync(recursive: true)
      ..writeAsStringSync(text);
    stdout.writeln('wrote $path');
  }
}
