/// Writes the golden-vector fixtures in `vectors/` from the Dart reference.
///
///     dart run tool/gen_vectors.dart            # write the fixtures
///     dart run tool/gen_vectors.dart --check    # exit 1 if a fixture is stale
///
/// Run from `dart/`. Each fixture records a function's inputs and the
/// outputs this package computes for them; every port tests against the
/// same files (SPEC.md, golden vectors).
