/// A camera looking down -Z, with screen axes on world X and Y.
final _axisAligned = (right: vm.Vector3(1, 0, 0), up: vm.Vector3(0, 1, 0));

/// A camera above a Z-up scene, looking along +Y.
final _zUp = (right: vm.Vector3(1, 0, 0), up: vm.Vector3(0, 0, 1));

/// An orthonormal basis with no axis aligned to the world's, so every
/// component of every output depends on both basis vectors.
final _oblique = (
  right: vm.Vector3(0.6, 0.8, 0),
  up: vm.Vector3(-0.48, 0.36, 0.8),
);

const _customStyle = LeaderLineStyle(
  lineWidth: 2,
  gapPixels: 8,
  angledLengthPixels: 40,
  horizontalLengthPixels: 30,
