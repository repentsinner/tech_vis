#!/usr/bin/env python3
"""Generate the per-language token modules from style/tokens.json.

    python3 tools/gen_tokens.py            # write the generated files
    python3 tools/gen_tokens.py --check    # exit 1 if a file is stale

Standard library only, so it runs before either package's environment exists.
The generated files are committed: a published package cannot read outside its
own directory, and the Dart constants have to stay `const`.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
import textwrap
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "style" / "tokens.json"
DART_OUT = ROOT / "dart" / "lib" / "src" / "style_tokens.g.dart"
PYTHON_OUT = ROOT / "python" / "src" / "tech_vis" / "tokens.py"

HEADER = "GENERATED by tools/gen_tokens.py from style/tokens.json. Do not edit."
DART_DOC_WIDTH = 72
PYTHON_DOC_WIDTH = 84


def load() -> tuple[int, dict[str, dict]]:
    data = json.loads(SOURCE.read_text())
    tokens = data["tokens"]
    for name, entry in tokens.items():
        if ("value" in entry) == ("alias" in entry):
            sys.exit(f"{name}: give exactly one of 'value' and 'alias'")
        if "alias" in entry and entry["alias"] not in tokens:
            sys.exit(f"{name}: alias '{entry['alias']}' is not a token")
    return data["styleVersion"], tokens


def screaming_snake(camel: str) -> str:
    return re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", camel).upper()


def doc_lines(entry: dict, width: int) -> list[str]:
    return textwrap.wrap(f"{entry['doc']} Unit: {entry['unit']}.", width)


def render_dart(version: int, tokens: dict[str, dict]) -> str:
    out = [
        f"// {HEADER}",
        "",
        "/// Style tokens shared by every tech_vis implementation.",
        "abstract final class StyleTokens {",
        "  /// Version of the token set. Implementations of one style version",
        "  /// produce the same layout.",
        f"  static const int styleVersion = {version};",
    ]
    for name, entry in tokens.items():
        out.append("")
        out += [f"  /// {line}" for line in doc_lines(entry, DART_DOC_WIDTH)]
        value = entry.get("alias", entry.get("value"))
        out.append(f"  static const double {name} = {value};")
    out += ["", "  /// Every token by its name in style/tokens.json."]
    out.append("  static const Map<String, double> all = {")
    out += [f"    '{name}': {name}," for name in tokens]
    out += ["  };", "}", ""]
    return "\n".join(out)


def render_python(version: int, tokens: dict[str, dict]) -> str:
    out = [
        f"# {HEADER}",
        '"""Style tokens shared by every tech_vis implementation."""',
        "",
        "# Version of the token set. Implementations of one style version produce",
        "# the same layout.",
        f"STYLE_VERSION: int = {version}",
    ]
    for name, entry in tokens.items():
        out.append("")
        out += [f"# {line}" for line in doc_lines(entry, PYTHON_DOC_WIDTH)]
        value = (
            screaming_snake(entry["alias"]) if "alias" in entry else entry["value"]
        )
        out.append(f"{screaming_snake(name)}: float = {value}")
    out += ["", "# Every token by its name in style/tokens.json."]
    out.append("ALL: dict[str, float] = {")
    out += [f'    "{name}": {screaming_snake(name)},' for name in tokens]
    out += ["}", ""]
    return "\n".join(out)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check", action="store_true", help="fail if a generated file is stale"
    )
    args = parser.parse_args()

    version, tokens = load()
    rendered = {
        DART_OUT: render_dart(version, tokens),
        PYTHON_OUT: render_python(version, tokens),
    }

    stale = [
        path
        for path, text in rendered.items()
        if not path.exists() or path.read_text() != text
    ]
    if args.check:
        for path in stale:
            print(f"stale: {path.relative_to(ROOT)}", file=sys.stderr)
        if stale:
            print("run: python3 tools/gen_tokens.py", file=sys.stderr)
        return 1 if stale else 0

    for path in stale:
        path.write_text(rendered[path])
        print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
